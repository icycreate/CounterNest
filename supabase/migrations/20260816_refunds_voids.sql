-- Expand sales lifecycle and retain adjustment totals/audit counters.
alter table public.sales drop constraint if exists sales_status_check;
alter table public.sales add constraint sales_status_check
  check (status in ('completed','partially_refunded','refunded','voided'));
alter table public.sales add column if not exists refunded_total numeric(12,2) not null default 0 check (refunded_total >= 0);
