alter table public.sales add column if not exists reprint_count int not null default 0 check (reprint_count >= 0);

create table if not exists public.sale_refunds (
  id uuid primary key default gen_random_uuid(),
  refund_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  sale_id uuid not null references public.sales(id) on delete cascade,
  refund_type text not null check (refund_type in ('partial','full','void')),
  subtotal numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0,
  tax numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0 check (total >= 0),
  reason text not null,
  restocked boolean not null default false,
  payment_note text,
  points_reversed int not null default 0,
  points_restored int not null default 0,
  stamps_reversed int not null default 0,
  stamps_restored int not null default 0,
  processed_by uuid references auth.users(id) on delete set null,
  approved_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.sale_refund_items (
  id uuid primary key default gen_random_uuid(),
  refund_id uuid not null references public.sale_refunds(id) on delete cascade,
  sale_id uuid not null references public.sales(id) on delete cascade,
  sale_item_id uuid not null references public.sale_items(id) on delete cascade,
  shop_id uuid not null references public.shops(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  qty numeric(12,3) not null check (qty > 0),
  unit_price numeric(12,2) not null,
  line_total numeric(12,2) not null,
  created_at timestamptz not null default now()
);

create table if not exists public.receipt_reprints (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  sale_id uuid not null references public.sales(id) on delete cascade,
  reprinted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists sale_refunds_sale_idx on public.sale_refunds(sale_id, created_at);
create index if not exists sale_refund_items_sale_item_idx on public.sale_refund_items(sale_item_id);
create index if not exists receipt_reprints_sale_idx on public.receipt_reprints(sale_id, created_at);

