-- CounterNest POS Phase 31.3: supplier profiles and ingredient purchase orders.

alter table public.suppliers add column if not exists address text;
alter table public.suppliers add column if not exists payment_terms_days integer not null default 0 check(payment_terms_days between 0 and 365);
alter table public.suppliers add column if not exists notes text;
alter table public.suppliers add column if not exists updated_at timestamptz not null default now();

create table if not exists public.ingredient_purchase_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  supplier_id uuid not null references public.suppliers(id) on delete restrict,
  status text not null default 'ordered' check(status in('ordered','partially_received','received','cancelled')),
  expected_date date,
  note text,
  created_by uuid not null references auth.users(id) on delete restrict,
  ordered_at timestamptz not null default now(),
  cancelled_by uuid references auth.users(id) on delete restrict,
  cancelled_at timestamptz,
  completed_at timestamptz
);

create table if not exists public.ingredient_purchase_order_items (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  order_id uuid not null references public.ingredient_purchase_orders(id) on delete restrict,
  ingredient_id uuid not null references public.ingredients(id) on delete restrict,
  ingredient_name text not null,
  base_unit text not null check(base_unit in('g','ml','each')),
  ordered_quantity numeric(14,3) not null check(ordered_quantity>0),
  expected_unit_cost numeric(14,6) not null check(expected_unit_cost>=0),
  received_quantity numeric(14,3) not null default 0 check(received_quantity>=0 and received_quantity<=ordered_quantity),
  line_total numeric(14,2) generated always as(round(ordered_quantity*expected_unit_cost,2)) stored,
  unique(order_id,ingredient_id)
);

create table if not exists public.ingredient_purchase_order_events (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  order_id uuid not null references public.ingredient_purchase_orders(id) on delete restrict,
  action text not null check(action in('ordered','partially_received','received','cancelled')),
  details jsonb not null default '{}'::jsonb,
  performed_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index if not exists ingredient_po_shop_date_idx on public.ingredient_purchase_orders(shop_id,ordered_at desc);
create index if not exists ingredient_po_items_order_idx on public.ingredient_purchase_order_items(order_id);
create index if not exists ingredient_po_events_order_idx on public.ingredient_purchase_order_events(order_id,created_at desc);

alter table public.ingredient_purchase_orders enable row level security;
alter table public.ingredient_purchase_order_items enable row level security;
alter table public.ingredient_purchase_order_events enable row level security;
drop policy if exists ingredient_po_admin_select on public.ingredient_purchase_orders;
create policy ingredient_po_admin_select on public.ingredient_purchase_orders for select to authenticated using(shop_id=public.current_shop_id() and public.is_admin());
drop policy if exists ingredient_po_items_admin_select on public.ingredient_purchase_order_items;
create policy ingredient_po_items_admin_select on public.ingredient_purchase_order_items for select to authenticated using(shop_id=public.current_shop_id() and public.is_admin());
drop policy if exists ingredient_po_events_admin_select on public.ingredient_purchase_order_events;
create policy ingredient_po_events_admin_select on public.ingredient_purchase_order_events for select to authenticated using(shop_id=public.current_shop_id() and public.is_admin());

create or replace function public.upsert_supplier_profile(
  p_supplier_id uuid,p_name text,p_contact_name text,p_phone text,p_email text,p_address text,p_payment_terms_days integer,p_notes text,p_active boolean
) returns uuid language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_id uuid;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if nullif(trim(p_name),'') is null then raise exception 'Supplier name is required'; end if;
  if coalesce(p_payment_terms_days,0)<0 or coalesce(p_payment_terms_days,0)>365 then raise exception 'Payment terms must be between 0 and 365 days'; end if;
  if p_supplier_id is null then
    insert into public.suppliers(shop_id,name,contact_name,phone,email,address,payment_terms_days,notes,active)
    values(v_shop,trim(p_name),nullif(trim(p_contact_name),''),nullif(trim(p_phone),''),nullif(lower(trim(p_email)),''),nullif(trim(p_address),''),coalesce(p_payment_terms_days,0),nullif(trim(p_notes),''),coalesce(p_active,true)) returning id into v_id;
  else
    update public.suppliers set name=trim(p_name),contact_name=nullif(trim(p_contact_name),''),phone=nullif(trim(p_phone),''),email=nullif(lower(trim(p_email)),''),address=nullif(trim(p_address),''),payment_terms_days=coalesce(p_payment_terms_days,0),notes=nullif(trim(p_notes),''),active=coalesce(p_active,true),updated_at=now()
    where id=p_supplier_id and shop_id=v_shop returning id into v_id;
    if v_id is null then raise exception 'Supplier not found'; end if;
  end if;
  return v_id;
end $$;

create or replace function public.create_ingredient_purchase_order(p_supplier_id uuid,p_expected_date date,p_note text,p_items jsonb)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_order uuid;v_item record;v_ingredient public.ingredients%rowtype;v_count integer:=0;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if not exists(select 1 from public.suppliers where id=p_supplier_id and shop_id=v_shop and active) then raise exception 'Active supplier not found'; end if;
  if p_expected_date is not null and p_expected_date<current_date then raise exception 'Expected date cannot be in the past'; end if;
  if jsonb_typeof(coalesce(p_items,'[]'::jsonb))<>'array' or jsonb_array_length(coalesce(p_items,'[]'::jsonb))=0 then raise exception 'At least one ingredient is required'; end if;
  insert into public.ingredient_purchase_orders(shop_id,supplier_id,expected_date,note,created_by)
  values(v_shop,p_supplier_id,p_expected_date,nullif(trim(p_note),''),auth.uid()) returning id into v_order;
  for v_item in select * from jsonb_to_recordset(p_items) as x(ingredient_id uuid,ordered_quantity numeric,expected_unit_cost numeric) loop
    select * into v_ingredient from public.ingredients where id=v_item.ingredient_id and shop_id=v_shop and active;
    if v_ingredient.id is null then raise exception 'Active ingredient not found'; end if;
    if v_item.ordered_quantity is null or v_item.ordered_quantity<=0 or coalesce(v_item.expected_unit_cost,-1)<0 then raise exception 'Valid quantity and expected cost are required'; end if;
    insert into public.ingredient_purchase_order_items(shop_id,order_id,ingredient_id,ingredient_name,base_unit,ordered_quantity,expected_unit_cost)
    values(v_shop,v_order,v_ingredient.id,v_ingredient.name,v_ingredient.base_unit,round(v_item.ordered_quantity,3),round(v_item.expected_unit_cost,6));
    v_count:=v_count+1;
  end loop;
  if v_count=0 then raise exception 'At least one ingredient is required'; end if;
  insert into public.ingredient_purchase_order_events(shop_id,order_id,action,performed_by) values(v_shop,v_order,'ordered',auth.uid());
  return v_order;
end $$;

create or replace function public.cancel_ingredient_purchase_order(p_order_id uuid) returns void
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  update public.ingredient_purchase_orders set status='cancelled',cancelled_by=auth.uid(),cancelled_at=now()
  where id=p_order_id and shop_id=v_shop and status in('ordered','partially_received');
  if not found then raise exception 'Open ingredient purchase order not found'; end if;
  insert into public.ingredient_purchase_order_events(shop_id,order_id,action,performed_by) values(v_shop,p_order_id,'cancelled',auth.uid());
end $$;

revoke all on function public.upsert_supplier_profile(uuid,text,text,text,text,text,integer,text,boolean) from public;
revoke all on function public.create_ingredient_purchase_order(uuid,date,text,jsonb) from public;
revoke all on function public.cancel_ingredient_purchase_order(uuid) from public;
grant execute on function public.upsert_supplier_profile(uuid,text,text,text,text,text,integer,text,boolean) to authenticated;
grant execute on function public.create_ingredient_purchase_order(uuid,date,text,jsonb) to authenticated;
grant execute on function public.cancel_ingredient_purchase_order(uuid) to authenticated;
