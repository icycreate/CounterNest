-- CounterNest POS Phase 31.4: partial ingredient receiving and purchase-cost variance.

create table if not exists public.ingredient_purchase_receipts (
  id uuid primary key default gen_random_uuid(),
  receipt_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  order_id uuid not null references public.ingredient_purchase_orders(id) on delete restrict,
  supplier_id uuid not null references public.suppliers(id) on delete restrict,
  invoice_reference text,
  note text,
  received_by uuid not null references auth.users(id) on delete restrict,
  received_at timestamptz not null default now()
);

create table if not exists public.ingredient_purchase_receipt_items (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  receipt_id uuid not null references public.ingredient_purchase_receipts(id) on delete restrict,
  order_item_id uuid not null references public.ingredient_purchase_order_items(id) on delete restrict,
  ingredient_id uuid not null references public.ingredients(id) on delete restrict,
  ingredient_name text not null,
  base_unit text not null check(base_unit in('g','ml','each')),
  quantity_received numeric(14,3) not null check(quantity_received>0),
  expected_unit_cost numeric(14,6) not null check(expected_unit_cost>=0),
  actual_unit_cost numeric(14,6) not null check(actual_unit_cost>=0),
  actual_total numeric(14,2) generated always as(round(quantity_received*actual_unit_cost,2)) stored,
  cost_variance numeric(14,2) generated always as(round(quantity_received*(actual_unit_cost-expected_unit_cost),2)) stored
);

create index if not exists ingredient_purchase_receipts_shop_idx on public.ingredient_purchase_receipts(shop_id,received_at desc);
create index if not exists ingredient_purchase_receipt_items_receipt_idx on public.ingredient_purchase_receipt_items(receipt_id);
alter table public.ingredient_purchase_receipts enable row level security;
alter table public.ingredient_purchase_receipt_items enable row level security;
drop policy if exists ingredient_purchase_receipts_admin_select on public.ingredient_purchase_receipts;
create policy ingredient_purchase_receipts_admin_select on public.ingredient_purchase_receipts for select to authenticated using(shop_id=public.current_shop_id() and public.is_admin());
drop policy if exists ingredient_purchase_receipt_items_admin_select on public.ingredient_purchase_receipt_items;
create policy ingredient_purchase_receipt_items_admin_select on public.ingredient_purchase_receipt_items for select to authenticated using(shop_id=public.current_shop_id() and public.is_admin());

create or replace function public.receive_ingredient_purchase_order(p_order_id uuid,p_invoice_reference text,p_note text,p_items jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_shop uuid:=public.current_shop_id();v_order public.ingredient_purchase_orders%rowtype;v_line record;v_order_item public.ingredient_purchase_order_items%rowtype;
  v_ingredient public.ingredients%rowtype;v_receipt uuid;v_balance numeric;v_average numeric;v_count integer:=0;v_new_status text;v_result jsonb:='[]'::jsonb;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  select * into v_order from public.ingredient_purchase_orders where id=p_order_id and shop_id=v_shop for update;
  if v_order.id is null or v_order.status not in('ordered','partially_received') then raise exception 'Open ingredient purchase order not found'; end if;
  if jsonb_typeof(coalesce(p_items,'[]'::jsonb))<>'array' or jsonb_array_length(coalesce(p_items,'[]'::jsonb))=0 then raise exception 'At least one receipt line is required'; end if;
  insert into public.ingredient_purchase_receipts(shop_id,order_id,supplier_id,invoice_reference,note,received_by)
  values(v_shop,v_order.id,v_order.supplier_id,nullif(trim(p_invoice_reference),''),nullif(trim(p_note),''),auth.uid()) returning id into v_receipt;
  for v_line in select * from jsonb_to_recordset(p_items) as x(order_item_id uuid,quantity_received numeric,actual_unit_cost numeric) loop
    select * into v_order_item from public.ingredient_purchase_order_items where id=v_line.order_item_id and order_id=v_order.id and shop_id=v_shop for update;
    if v_order_item.id is null then raise exception 'Purchase-order line not found'; end if;
    if v_line.quantity_received is null or v_line.quantity_received<=0 or v_line.quantity_received>v_order_item.ordered_quantity-v_order_item.received_quantity then raise exception 'Received quantity exceeds the remaining ordered quantity for %',v_order_item.ingredient_name; end if;
    if v_line.actual_unit_cost is null or v_line.actual_unit_cost<0 then raise exception 'Actual unit cost cannot be negative'; end if;
    select * into v_ingredient from public.ingredients where id=v_order_item.ingredient_id and shop_id=v_shop for update;
    if v_ingredient.id is null then raise exception 'Ingredient not found'; end if;
    v_balance:=v_ingredient.current_quantity+v_line.quantity_received;
    v_average:=case when v_balance=0 then 0 else ((v_ingredient.current_quantity*v_ingredient.average_unit_cost)+(v_line.quantity_received*v_line.actual_unit_cost))/v_balance end;
    insert into public.ingredient_purchase_receipt_items(shop_id,receipt_id,order_item_id,ingredient_id,ingredient_name,base_unit,quantity_received,expected_unit_cost,actual_unit_cost)
    values(v_shop,v_receipt,v_order_item.id,v_ingredient.id,v_ingredient.name,v_ingredient.base_unit,round(v_line.quantity_received,3),v_order_item.expected_unit_cost,round(v_line.actual_unit_cost,6));
    update public.ingredient_purchase_order_items set received_quantity=received_quantity+round(v_line.quantity_received,3) where id=v_order_item.id;
    update public.ingredients set current_quantity=v_balance,average_unit_cost=round(v_average,6),preferred_supplier_id=v_order.supplier_id,updated_at=now() where id=v_ingredient.id;
    insert into public.ingredient_inventory_movements(shop_id,ingredient_id,movement_type,quantity_delta,unit_cost,balance_after,reason,reference_type,reference_id,created_by)
    values(v_shop,v_ingredient.id,'receipt',round(v_line.quantity_received,3),round(v_line.actual_unit_cost,6),v_balance,'Ingredient purchase order IPO-'||v_order.order_number||' received','ingredient_purchase_receipt',v_receipt,auth.uid());
    v_result:=v_result||jsonb_build_array(jsonb_build_object('ingredient_id',v_ingredient.id,'new_balance',v_balance,'average_unit_cost',round(v_average,6)));
    v_count:=v_count+1;
  end loop;
  if v_count=0 then raise exception 'At least one positive receipt line is required'; end if;
  if exists(select 1 from public.ingredient_purchase_order_items where order_id=v_order.id and received_quantity<ordered_quantity) then v_new_status:='partially_received'; else v_new_status:='received'; end if;
  update public.ingredient_purchase_orders set status=v_new_status,completed_at=case when v_new_status='received' then now() else null end where id=v_order.id;
  insert into public.ingredient_purchase_order_events(shop_id,order_id,action,details,performed_by)
  values(v_shop,v_order.id,v_new_status,jsonb_build_object('receipt_id',v_receipt,'invoice_reference',nullif(trim(p_invoice_reference),'')),auth.uid());
  return jsonb_build_object('receipt_id',v_receipt,'order_id',v_order.id,'status',v_new_status,'ingredients',v_result);
end $$;

revoke all on function public.receive_ingredient_purchase_order(uuid,text,text,jsonb) from public;
grant execute on function public.receive_ingredient_purchase_order(uuid,text,text,jsonb) to authenticated;
