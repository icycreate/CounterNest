-- CounterNest POS Phase 31.5: auditable ingredient and finished-product waste.

create table if not exists public.inventory_waste_events (
  id uuid primary key default gen_random_uuid(),
  waste_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  source_type text not null check(source_type in('ingredient','product')),
  ingredient_id uuid references public.ingredients(id) on delete restrict,
  product_id uuid references public.products(id) on delete restrict,
  item_name text not null,
  quantity numeric(14,3) not null check(quantity>0),
  unit text not null,
  unit_cost_snapshot numeric(14,6) not null check(unit_cost_snapshot>=0),
  total_cost numeric(14,2) generated always as(round(quantity*unit_cost_snapshot,2)) stored,
  reason_category text not null check(reason_category in('expired','damaged','quality','overproduction','handling','count_correction','other')),
  note text,
  production_batch_id uuid references public.production_batches(id) on delete set null,
  recorded_by uuid not null references auth.users(id) on delete restrict,
  recorded_at timestamptz not null default now(),
  constraint waste_source_match check((source_type='ingredient' and ingredient_id is not null and product_id is null) or(source_type='product' and product_id is not null and ingredient_id is null))
);

create index if not exists inventory_waste_shop_date_idx on public.inventory_waste_events(shop_id,recorded_at desc);
alter table public.inventory_waste_events enable row level security;
drop policy if exists inventory_waste_admin_select on public.inventory_waste_events;
create policy inventory_waste_admin_select on public.inventory_waste_events for select to authenticated using(shop_id=public.current_shop_id() and public.is_admin());

create or replace function public.record_inventory_waste(p_source_type text,p_item_id uuid,p_quantity numeric,p_reason_category text,p_note text,p_production_batch_id uuid default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_ingredient public.ingredients%rowtype;v_product public.products%rowtype;v_id uuid;v_balance numeric;v_name text;v_unit text;v_cost numeric;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_source_type not in('ingredient','product') then raise exception 'Waste source must be ingredient or product'; end if;
  if p_quantity is null or p_quantity<=0 then raise exception 'Waste quantity must be greater than zero'; end if;
  if p_reason_category not in('expired','damaged','quality','overproduction','handling','count_correction','other') then raise exception 'Select a valid waste reason'; end if;
  if p_production_batch_id is not null and not exists(select 1 from public.production_batches where id=p_production_batch_id and shop_id=v_shop) then raise exception 'Production batch not found'; end if;
  if p_source_type='ingredient' then
    select * into v_ingredient from public.ingredients where id=p_item_id and shop_id=v_shop for update;
    if v_ingredient.id is null then raise exception 'Ingredient not found'; end if;
    if v_ingredient.current_quantity<p_quantity then raise exception 'Waste quantity exceeds available ingredient stock'; end if;
    v_balance:=v_ingredient.current_quantity-p_quantity;v_name:=v_ingredient.name;v_unit:=v_ingredient.base_unit;v_cost:=v_ingredient.average_unit_cost;
    insert into public.inventory_waste_events(shop_id,source_type,ingredient_id,item_name,quantity,unit,unit_cost_snapshot,reason_category,note,production_batch_id,recorded_by)
    values(v_shop,'ingredient',v_ingredient.id,v_name,round(p_quantity,3),v_unit,v_cost,p_reason_category,nullif(trim(p_note),''),p_production_batch_id,auth.uid()) returning id into v_id;
    update public.ingredients set current_quantity=v_balance,updated_at=now() where id=v_ingredient.id;
    insert into public.ingredient_inventory_movements(shop_id,ingredient_id,movement_type,quantity_delta,unit_cost,balance_after,reason,reference_type,reference_id,created_by)
    values(v_shop,v_ingredient.id,'waste',-round(p_quantity,3),v_cost,v_balance,'Waste: '||replace(p_reason_category,'_',' '),'waste_event',v_id,auth.uid());
  else
    select * into v_product from public.products where id=p_item_id and shop_id=v_shop for update;
    if v_product.id is null then raise exception 'Product not found'; end if;
    if v_product.stock<p_quantity then raise exception 'Waste quantity exceeds available product stock'; end if;
    v_balance:=v_product.stock-p_quantity;v_name:=v_product.name;v_unit:='each';v_cost:=coalesce(v_product.cost_price,0);
    insert into public.inventory_waste_events(shop_id,source_type,product_id,item_name,quantity,unit,unit_cost_snapshot,reason_category,note,production_batch_id,recorded_by)
    values(v_shop,'product',v_product.id,v_name,round(p_quantity,3),v_unit,v_cost,p_reason_category,nullif(trim(p_note),''),p_production_batch_id,auth.uid()) returning id into v_id;
    update public.products set stock=v_balance,updated_at=now() where id=v_product.id;
    insert into public.inventory_adjustments(shop_id,product_id,delta,reason,created_by)
    values(v_shop,v_product.id,-round(p_quantity,3),'Waste W-'||v_id||': '||replace(p_reason_category,'_',' '),auth.uid());
  end if;
  return jsonb_build_object('waste_id',v_id,'source_type',p_source_type,'item_id',p_item_id,'new_balance',v_balance,'estimated_cost',round(p_quantity*v_cost,2));
end $$;

revoke all on function public.record_inventory_waste(text,uuid,numeric,text,text,uuid) from public;
grant execute on function public.record_inventory_waste(text,uuid,numeric,text,text,uuid) to authenticated;
