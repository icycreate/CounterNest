-- CounterNest POS v1.13.0 / Phase 33.0
-- Post-go-live operational health and immutable incident management.

create table if not exists public.operational_incidents (
  id uuid primary key default gen_random_uuid(),
  incident_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  severity text not null check(severity in('low','medium','high','critical')),
  category text not null check(category in('checkout','payment','inventory','loyalty','daily_cash','authentication','device','network','printing','data','other')),
  title text not null check(length(trim(title)) between 5 and 120),
  description text not null check(length(trim(description)) between 10 and 4000),
  impact text,
  status text not null default 'open' check(status in('open','investigating','monitoring','resolved')),
  reported_by uuid not null references auth.users(id) on delete restrict,
  reported_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_by uuid references auth.users(id) on delete restrict,
  resolved_at timestamptz,
  resolution_note text,
  constraint operational_incident_resolution_fields check(
    (status='resolved' and resolved_by is not null and resolved_at is not null and length(trim(coalesce(resolution_note,'')))>=5)
    or
    (status<>'resolved' and resolved_by is null and resolved_at is null)
  )
);

create index if not exists operational_incidents_shop_status_idx on public.operational_incidents(shop_id,status,reported_at desc);
create index if not exists operational_incidents_shop_severity_idx on public.operational_incidents(shop_id,severity,reported_at desc);

create table if not exists public.operational_incident_events (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  incident_id uuid not null references public.operational_incidents(id) on delete restrict,
  action text not null check(action in('opened','status_changed','note_added','resolved','reopened')),
  from_status text,
  to_status text,
  note text,
  details jsonb not null default '{}'::jsonb,
  performed_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index if not exists operational_incident_events_incident_idx on public.operational_incident_events(incident_id,created_at desc);

alter table public.operational_incidents enable row level security;
alter table public.operational_incident_events enable row level security;
drop policy if exists operational_incidents_admin_select on public.operational_incidents;
create policy operational_incidents_admin_select on public.operational_incidents for select to authenticated
using(shop_id=public.current_shop_id() and public.is_admin());
drop policy if exists operational_incident_events_admin_select on public.operational_incident_events;
create policy operational_incident_events_admin_select on public.operational_incident_events for select to authenticated
using(shop_id=public.current_shop_id() and public.is_admin());

create or replace function public.create_operational_incident(
  p_severity text,p_category text,p_title text,p_description text,p_impact text default null
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_id uuid;v_number bigint;v_reference text;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_severity not in('low','medium','high','critical') then raise exception 'Invalid incident severity'; end if;
  if p_category not in('checkout','payment','inventory','loyalty','daily_cash','authentication','device','network','printing','data','other') then raise exception 'Invalid incident category'; end if;
  if length(trim(coalesce(p_title,'')))<5 then raise exception 'Incident title must contain at least 5 characters'; end if;
  if length(trim(coalesce(p_description,'')))<10 then raise exception 'Incident description must contain at least 10 characters'; end if;
  insert into public.operational_incidents(shop_id,severity,category,title,description,impact,reported_by)
  values(v_shop,p_severity,p_category,trim(p_title),trim(p_description),nullif(trim(p_impact),''),auth.uid())
  returning id,incident_number into v_id,v_number;
  v_reference:='INC-'||to_char(public.current_business_date(),'YYYY')||'-'||lpad(v_number::text,6,'0');
  insert into public.operational_incident_events(shop_id,incident_id,action,to_status,note,details,performed_by)
  values(v_shop,v_id,'opened','open',trim(p_description),jsonb_build_object('reference',v_reference,'severity',p_severity,'category',p_category,'impact',nullif(trim(p_impact),'')),auth.uid());
  return jsonb_build_object('id',v_id,'incident_number',v_number,'reference',v_reference,'status','open');
end $$;

create or replace function public.update_operational_incident(
  p_incident_id uuid,p_status text,p_note text
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.operational_incidents%rowtype;v_action text;v_reference text;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_status not in('open','investigating','monitoring','resolved') then raise exception 'Invalid incident status'; end if;
  select * into v_row from public.operational_incidents where id=p_incident_id and shop_id=v_shop for update;
  if v_row.id is null then raise exception 'Operational incident not found'; end if;
  if length(trim(coalesce(p_note,'')))<5 then raise exception 'An incident update note of at least 5 characters is required'; end if;
  if p_status='resolved' then v_action:='resolved';
  elsif v_row.status='resolved' then v_action:='reopened';
  elsif p_status=v_row.status then v_action:='note_added';
  else v_action:='status_changed'; end if;
  update public.operational_incidents set
    status=p_status,updated_at=now(),
    resolved_by=case when p_status='resolved' then auth.uid() else null end,
    resolved_at=case when p_status='resolved' then now() else null end,
    resolution_note=case when p_status='resolved' then trim(p_note) else resolution_note end
  where id=v_row.id;
  insert into public.operational_incident_events(shop_id,incident_id,action,from_status,to_status,note,performed_by)
  values(v_shop,v_row.id,v_action,v_row.status,p_status,trim(p_note),auth.uid());
  v_reference:='INC-'||to_char(v_row.reported_at at time zone coalesce((select timezone from public.shops where id=v_shop),'UTC'),'YYYY')||'-'||lpad(v_row.incident_number::text,6,'0');
  return jsonb_build_object('id',v_row.id,'reference',v_reference,'status',p_status,'action',v_action,'updated_at',now());
end $$;

create or replace function public.get_phase33_operations() returns jsonb
language plpgsql security definer stable set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_date date:=public.current_business_date();
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  return jsonb_build_object(
    'business_date',v_date,
    'metrics',jsonb_build_object(
      'open_incidents',(select count(*) from public.operational_incidents where shop_id=v_shop and status<>'resolved'),
      'critical_incidents',(select count(*) from public.operational_incidents where shop_id=v_shop and status<>'resolved' and severity='critical'),
      'resolved_incidents',(select count(*) from public.operational_incidents where shop_id=v_shop and status='resolved'),
      'oldest_open_hours',(select coalesce(floor(extract(epoch from(now()-min(reported_at)))/3600),0) from public.operational_incidents where shop_id=v_shop and status<>'resolved')
    ),
    'health_checks',jsonb_build_array(
      jsonb_build_object('id','critical_incidents','label','Critical incidents','status',case when exists(select 1 from public.operational_incidents where shop_id=v_shop and status<>'resolved' and severity='critical') then 'fail' else 'pass' end,'detail','No unresolved critical incident may be ignored.'),
      jsonb_build_object('id','aging_incidents','label','Incident response','status',case when exists(select 1 from public.operational_incidents where shop_id=v_shop and status<>'resolved' and reported_at<now()-interval '24 hours') then 'warning' else 'pass' end,'detail','Review every incident that remains open longer than 24 hours.'),
      jsonb_build_object('id','daily_cash','label','Daily Cash continuity','status',case when exists(select 1 from public.cash_drawer_sessions where shop_id=v_shop and status='open' and business_date<v_date) then 'fail' else 'pass' end,'detail','No prior-date Daily Cash record may remain open.'),
      jsonb_build_object('id','recent_backup','label','Recent protected backup','status',case when exists(select 1 from public.backup_exports where shop_id=v_shop and requested_at>=now()-interval '7 days') then 'pass' else 'warning' end,'detail','Keep a verified operational backup no more than seven days old.'),
      jsonb_build_object('id','open_recalls','label','Recall cases','status',case when exists(select 1 from public.finished_product_recall_cases where shop_id=v_shop and status='open') then 'warning' else 'pass' end,'detail','Open recall cases require active management.'),
      jsonb_build_object('id','go_live_approval','label','Internal go-live evidence','status',case when exists(select 1 from public.phase32_go_live_reviews where shop_id=v_shop and status='approved') then 'pass' else 'warning' end,'detail','Retain an approved Phase 32 production review before normal operation.')
    ),
    'incidents',(select coalesce(jsonb_agg(to_jsonb(x) order by x.reported_at desc),'[]'::jsonb) from(
      select i.id,i.incident_number,'INC-'||to_char(i.reported_at at time zone coalesce(sh.timezone,'UTC'),'YYYY')||'-'||lpad(i.incident_number::text,6,'0') reference,
        i.severity,i.category,i.title,i.description,i.impact,i.status,i.reported_at,i.updated_at,i.resolved_at,i.resolution_note,
        coalesce(reporter.display_name,'Former administrator') reported_by_name,coalesce(resolver.display_name,'—') resolved_by_name,
        (select count(*) from public.operational_incident_events e where e.incident_id=i.id) event_count
      from public.operational_incidents i join public.shops sh on sh.id=i.shop_id
      left join public.staff_profiles reporter on reporter.user_id=i.reported_by and reporter.shop_id=i.shop_id
      left join public.staff_profiles resolver on resolver.user_id=i.resolved_by and resolver.shop_id=i.shop_id
      where i.shop_id=v_shop order by i.reported_at desc limit 250
    )x),
    'events',(select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) from(
      select e.id,e.incident_id,e.action,e.from_status,e.to_status,e.note,e.created_at,coalesce(sp.display_name,'Former administrator') performed_by_name
      from public.operational_incident_events e left join public.staff_profiles sp on sp.user_id=e.performed_by and sp.shop_id=e.shop_id
      where e.shop_id=v_shop order by e.created_at desc limit 500
    )x)
  );
end $$;

-- Extend the established business export without modifying the Phase 32 base export.
alter function public.export_business_backup() rename to export_business_backup_phase32_base;
revoke all on function public.export_business_backup_phase32_base() from public;
revoke all on function public.export_business_backup_phase32_base() from authenticated;
create or replace function public.export_business_backup() returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_base jsonb;v_export uuid;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  v_base:=public.export_business_backup_phase32_base();
  v_export:=(v_base->>'export_id')::uuid;
  update public.backup_exports set schema_version='1.13.0' where id=v_export and shop_id=v_shop;
  return (v_base-'schema_version')||jsonb_build_object(
    'schema_version','1.13.0',
    'operational_incidents',(select coalesce(jsonb_agg(to_jsonb(t)),'[]'::jsonb) from public.operational_incidents t where shop_id=v_shop),
    'operational_incident_events',(select coalesce(jsonb_agg(to_jsonb(t)),'[]'::jsonb) from public.operational_incident_events t where shop_id=v_shop)
  );
end $$;

