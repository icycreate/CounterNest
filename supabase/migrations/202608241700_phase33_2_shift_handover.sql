-- CounterNest POS v1.15.0 / Phase 33.2
-- Structured shift handover, acknowledgement, closure, and immutable events.

create table if not exists public.shift_handovers(
  id uuid primary key default gen_random_uuid(),
  handover_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  business_date date not null,
  shift_label text not null check(shift_label in('opening','morning','afternoon','evening','closing','other')),
  summary text not null check(length(trim(summary)) between 10 and 4000),
  pending_actions text not null check(length(trim(pending_actions)) between 3 and 4000),
  stock_notes text,
  equipment_notes text,
  incident_references text[] not null default '{}'::text[],
  status text not null default 'open' check(status in('open','closed')),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  closed_by uuid references auth.users(id) on delete restrict,
  closed_at timestamptz,
  closing_note text,
  constraint shift_handover_close_fields check(
    (status='open' and closed_by is null and closed_at is null)
    or
    (status='closed' and closed_by is not null and closed_at is not null and length(trim(coalesce(closing_note,'')))>=5)
  )
);
create index if not exists shift_handovers_shop_date_idx on public.shift_handovers(shop_id,business_date desc,created_at desc);

create table if not exists public.shift_handover_acknowledgements(
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  handover_id uuid not null references public.shift_handovers(id) on delete restrict,
  acknowledged_by uuid not null references auth.users(id) on delete restrict,
  acknowledgement_note text not null check(length(trim(acknowledgement_note)) between 3 and 1000),
  acknowledged_at timestamptz not null default now(),
  unique(handover_id,acknowledged_by)
);
create index if not exists shift_handover_ack_shop_idx on public.shift_handover_acknowledgements(shop_id,handover_id,acknowledged_at);

create table if not exists public.shift_handover_events(
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  handover_id uuid not null references public.shift_handovers(id) on delete restrict,
  action text not null check(action in('created','acknowledged','closed')),
  details jsonb not null default '{}'::jsonb,
  performed_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);
create index if not exists shift_handover_events_handover_idx on public.shift_handover_events(handover_id,created_at);

alter table public.shift_handovers enable row level security;
alter table public.shift_handover_acknowledgements enable row level security;
alter table public.shift_handover_events enable row level security;
drop policy if exists shift_handovers_staff_select on public.shift_handovers;
create policy shift_handovers_staff_select on public.shift_handovers for select to authenticated using(
  shop_id=public.current_shop_id() and exists(select 1 from public.staff_profiles where user_id=auth.uid() and shop_id=shift_handovers.shop_id and active)
);
drop policy if exists shift_handover_ack_staff_select on public.shift_handover_acknowledgements;
create policy shift_handover_ack_staff_select on public.shift_handover_acknowledgements for select to authenticated using(
  shop_id=public.current_shop_id() and exists(select 1 from public.staff_profiles where user_id=auth.uid() and shop_id=shift_handover_acknowledgements.shop_id and active)
);
drop policy if exists shift_handover_events_staff_select on public.shift_handover_events;
create policy shift_handover_events_staff_select on public.shift_handover_events for select to authenticated using(
  shop_id=public.current_shop_id() and exists(select 1 from public.staff_profiles where user_id=auth.uid() and shop_id=shift_handover_events.shop_id and active)
);

create or replace function public.create_shift_handover(
  p_shift_label text,p_summary text,p_pending_actions text,p_stock_notes text default null,
  p_equipment_notes text default null,p_incident_references text[] default '{}'
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_id uuid;v_number bigint;v_reference text;v_refs text[];
begin
  if auth.uid() is null or v_shop is null or not exists(select 1 from public.staff_profiles where user_id=auth.uid() and shop_id=v_shop and active) then raise exception 'Active staff access required'; end if;
  if p_shift_label not in('opening','morning','afternoon','evening','closing','other') then raise exception 'Invalid shift label'; end if;
  if length(trim(coalesce(p_summary,'')))<10 then raise exception 'Handover summary must contain at least 10 characters'; end if;
  if length(trim(coalesce(p_pending_actions,'')))<3 then raise exception 'Pending actions must contain at least 3 characters; enter None when there are no pending actions'; end if;
  select coalesce(array_agg(distinct upper(trim(refs.value))) filter(where trim(refs.value)<>''),'{}'::text[]) into v_refs from unnest(coalesce(p_incident_references,'{}'::text[])) as refs(value);
  if exists(select 1 from unnest(v_refs) as refs(value) where refs.value!~'^INC-[0-9]{4}-[0-9]{6}$') then raise exception 'Incident references must use the format INC-YYYY-000000'; end if;
  insert into public.shift_handovers(shop_id,business_date,shift_label,summary,pending_actions,stock_notes,equipment_notes,incident_references,created_by)
  values(v_shop,public.current_business_date(),p_shift_label,trim(p_summary),trim(p_pending_actions),nullif(trim(p_stock_notes),''),nullif(trim(p_equipment_notes),''),v_refs,auth.uid())
  returning id,handover_number into v_id,v_number;
  v_reference:='HO-'||to_char(public.current_business_date(),'YYYYMMDD')||'-'||lpad(v_number::text,6,'0');
  insert into public.shift_handover_events(shop_id,handover_id,action,details,performed_by)
  values(v_shop,v_id,'created',jsonb_build_object('reference',v_reference,'shift_label',p_shift_label,'incident_references',v_refs),auth.uid());
  return jsonb_build_object('id',v_id,'reference',v_reference,'business_date',public.current_business_date(),'status','open');
end $$;

create or replace function public.acknowledge_shift_handover(p_handover_id uuid,p_note text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.shift_handovers%rowtype;v_id uuid;v_reference text;
begin
  if auth.uid() is null or v_shop is null or not exists(select 1 from public.staff_profiles where user_id=auth.uid() and shop_id=v_shop and active) then raise exception 'Active staff access required'; end if;
  if length(trim(coalesce(p_note,'')))<3 then raise exception 'Acknowledgement note must contain at least 3 characters'; end if;
  select * into v_row from public.shift_handovers where id=p_handover_id and shop_id=v_shop for update;
  if v_row.id is null then raise exception 'Shift handover not found'; end if;
  if v_row.status<>'open' then raise exception 'Closed shift handovers cannot be acknowledged'; end if;
  if v_row.created_by=auth.uid() then raise exception 'The staff member who created a handover cannot acknowledge their own handover'; end if;
  insert into public.shift_handover_acknowledgements(shop_id,handover_id,acknowledged_by,acknowledgement_note)
  values(v_shop,v_row.id,auth.uid(),trim(p_note)) returning id into v_id;
  insert into public.shift_handover_events(shop_id,handover_id,action,details,performed_by)
  values(v_shop,v_row.id,'acknowledged',jsonb_build_object('acknowledgement_id',v_id,'note',trim(p_note)),auth.uid());
  v_reference:='HO-'||to_char(v_row.business_date,'YYYYMMDD')||'-'||lpad(v_row.handover_number::text,6,'0');
  return jsonb_build_object('id',v_id,'handover_id',v_row.id,'reference',v_reference,'acknowledged_at',now());
exception when unique_violation then raise exception 'You already acknowledged this shift handover';
end $$;

create or replace function public.close_shift_handover(p_handover_id uuid,p_note text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.shift_handovers%rowtype;v_reference text;v_ack_count integer;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if length(trim(coalesce(p_note,'')))<5 then raise exception 'Closing note must contain at least 5 characters'; end if;
  select * into v_row from public.shift_handovers where id=p_handover_id and shop_id=v_shop for update;
  if v_row.id is null or v_row.status<>'open' then raise exception 'Open shift handover not found'; end if;
  select count(*) into v_ack_count from public.shift_handover_acknowledgements where handover_id=v_row.id;
  if v_ack_count<1 then raise exception 'At least one incoming staff acknowledgement is required before management closure'; end if;
  update public.shift_handovers set status='closed',closing_note=trim(p_note),closed_by=auth.uid(),closed_at=now() where id=v_row.id;
  insert into public.shift_handover_events(shop_id,handover_id,action,details,performed_by)
  values(v_shop,v_row.id,'closed',jsonb_build_object('note',trim(p_note),'acknowledgement_count',v_ack_count),auth.uid());
  v_reference:='HO-'||to_char(v_row.business_date,'YYYYMMDD')||'-'||lpad(v_row.handover_number::text,6,'0');
  return jsonb_build_object('id',v_row.id,'reference',v_reference,'status','closed','acknowledgement_count',v_ack_count,'closed_at',now());
end $$;

create or replace function public.get_shift_handovers(p_limit integer default 40) returns jsonb
language plpgsql security definer stable set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_limit integer:=greatest(1,least(coalesce(p_limit,40),100));
begin
  if auth.uid() is null or v_shop is null or not exists(select 1 from public.staff_profiles where user_id=auth.uid() and shop_id=v_shop and active) then raise exception 'Active staff access required'; end if;
  return coalesce((select jsonb_agg(to_jsonb(x) order by x.created_at desc) from(
    select h.id,'HO-'||to_char(h.business_date,'YYYYMMDD')||'-'||lpad(h.handover_number::text,6,'0') reference,
      h.business_date,h.shift_label,h.summary,h.pending_actions,h.stock_notes,h.equipment_notes,h.incident_references,h.status,h.created_at,h.closed_at,h.closing_note,
      h.created_by=auth.uid() created_by_me,coalesce(creator.display_name,'Former staff') created_by_name,coalesce(closer.display_name,'—') closed_by_name,
      exists(select 1 from public.shift_handover_acknowledgements a where a.handover_id=h.id and a.acknowledged_by=auth.uid()) acknowledged_by_me,
      (select count(*) from public.shift_handover_acknowledgements a where a.handover_id=h.id) acknowledgement_count,
      (select coalesce(jsonb_agg(jsonb_build_object('id',a.id,'note',a.acknowledgement_note,'acknowledged_at',a.acknowledged_at,'staff_name',coalesce(sp.display_name,'Former staff')) order by a.acknowledged_at),'[]'::jsonb)
        from public.shift_handover_acknowledgements a left join public.staff_profiles sp on sp.user_id=a.acknowledged_by and sp.shop_id=a.shop_id where a.handover_id=h.id) acknowledgements
    from public.shift_handovers h
    left join public.staff_profiles creator on creator.user_id=h.created_by and creator.shop_id=h.shop_id
    left join public.staff_profiles closer on closer.user_id=h.closed_by and closer.shop_id=h.shop_id
    where h.shop_id=v_shop order by h.created_at desc limit v_limit
  )x),'[]'::jsonb);
end $$;

alter function public.export_business_backup() rename to export_business_backup_phase33_base;
revoke all on function public.export_business_backup_phase33_base() from public;
