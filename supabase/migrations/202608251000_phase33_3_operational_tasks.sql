-- CounterNest POS v1.16.0 / Phase 33.3
-- Operational task assignment, acceptance, completion, management verification, and immutable evidence.

create table if not exists public.operational_tasks(
  id uuid primary key default gen_random_uuid(),
  task_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  business_date date not null,
  title text not null check(length(trim(title)) between 5 and 120),
  description text not null check(length(trim(description)) between 5 and 4000),
  priority text not null default 'normal' check(priority in('low','normal','high','urgent')),
  status text not null default 'open' check(status in('open','accepted','completed','verified','cancelled')),
  source_type text not null default 'general' check(source_type in('general','handover','incident')),
  source_reference text,
  assigned_to uuid references auth.users(id) on delete restrict,
  due_at timestamptz,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  accepted_by uuid references auth.users(id) on delete restrict,
  accepted_at timestamptz,
  completed_by uuid references auth.users(id) on delete restrict,
  completed_at timestamptz,
  completion_note text,
  verified_by uuid references auth.users(id) on delete restrict,
  verified_at timestamptz,
  verification_note text,
  updated_at timestamptz not null default now(),
  constraint operational_task_accept_fields check((status='open' and accepted_by is null and accepted_at is null) or status<>'open'),
  constraint operational_task_complete_fields check(status not in('completed','verified') or (completed_by is not null and completed_at is not null and length(trim(coalesce(completion_note,'')))>=5)),
  constraint operational_task_verify_fields check(status<>'verified' or (verified_by is not null and verified_at is not null and length(trim(coalesce(verification_note,'')))>=5)),
  constraint operational_task_source_fields check((source_type='general' and source_reference is null) or (source_type<>'general' and length(trim(coalesce(source_reference,'')))>0))
);
create index if not exists operational_tasks_shop_status_idx on public.operational_tasks(shop_id,status,due_at,created_at desc);
create index if not exists operational_tasks_assigned_idx on public.operational_tasks(shop_id,assigned_to,status);

create table if not exists public.operational_task_events(
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  task_id uuid not null references public.operational_tasks(id) on delete restrict,
  action text not null check(action in('created','assigned','accepted','completed','verified','reopened','cancelled')),
  from_status text,
  to_status text not null,
  note text,
  details jsonb not null default '{}'::jsonb,
  performed_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);
create index if not exists operational_task_events_task_idx on public.operational_task_events(task_id,created_at);

alter table public.operational_tasks enable row level security;
alter table public.operational_task_events enable row level security;
drop policy if exists operational_tasks_staff_select on public.operational_tasks;
create policy operational_tasks_staff_select on public.operational_tasks for select to authenticated using(shop_id=public.current_shop_id());
drop policy if exists operational_task_events_staff_select on public.operational_task_events;
create policy operational_task_events_staff_select on public.operational_task_events for select to authenticated using(shop_id=public.current_shop_id());

create or replace function public.create_operational_task(
  p_title text,p_description text,p_priority text default 'normal',p_assigned_to uuid default null,
  p_due_at timestamptz default null,p_source_type text default 'general',p_source_reference text default null
) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_assigned uuid:=p_assigned_to;v_id uuid;v_number bigint;v_business_date date;v_reference text;v_source text:=upper(trim(coalesce(p_source_reference,'')));
begin
  if auth.uid() is null or v_shop is null then raise exception 'Active staff access required'; end if;
  if length(trim(coalesce(p_title,'')))<5 or length(trim(coalesce(p_description,'')))<5 then raise exception 'Task title and description must each contain at least 5 characters'; end if;
  if p_priority not in('low','normal','high','urgent') then raise exception 'Invalid task priority'; end if;
  if p_source_type not in('general','handover','incident') then raise exception 'Invalid task source'; end if;
  if not public.is_admin() then v_assigned:=auth.uid(); end if;
  if v_assigned is not null and not exists(select 1 from public.staff_profiles where shop_id=v_shop and user_id=v_assigned and active) then raise exception 'Assigned staff member is not active in this shop'; end if;
  if p_source_type='general' then v_source:=null;
  elsif p_source_type='incident' then
    if v_source!~'^INC-[0-9]{4}-[0-9]{6}$' or not exists(select 1 from public.operational_incidents i where i.shop_id=v_shop and 'INC-'||to_char(i.reported_at at time zone coalesce((select timezone from public.shops where id=v_shop),'UTC'),'YYYY')||'-'||lpad(i.incident_number::text,6,'0')=v_source) then raise exception 'A valid incident reference from this shop is required'; end if;
  elsif p_source_type='handover' then
    if v_source!~'^HO-[0-9]{8}-[0-9]{6}$' or not exists(select 1 from public.shift_handovers h where h.shop_id=v_shop and 'HO-'||to_char(h.business_date,'YYYYMMDD')||'-'||lpad(h.handover_number::text,6,'0')=v_source) then raise exception 'A valid handover reference from this shop is required'; end if;
  end if;
  insert into public.operational_tasks(shop_id,business_date,title,description,priority,source_type,source_reference,assigned_to,due_at,created_by)
  values(v_shop,public.current_business_date(),trim(p_title),trim(p_description),p_priority,p_source_type,v_source,v_assigned,p_due_at,auth.uid()) returning id,task_number,business_date into v_id,v_number,v_business_date;
  v_reference:='TASK-'||to_char(v_business_date,'YYYYMMDD')||'-'||lpad(v_number::text,6,'0');
  insert into public.operational_task_events(shop_id,task_id,action,from_status,to_status,note,details,performed_by)
  values(v_shop,v_id,'created',null,'open',null,jsonb_build_object('reference',v_reference,'priority',p_priority,'assigned_to',v_assigned,'due_at',p_due_at,'source_type',p_source_type,'source_reference',v_source),auth.uid());
  return jsonb_build_object('id',v_id,'reference',v_reference,'status','open');
end $$;

create or replace function public.assign_operational_task(p_task_id uuid,p_assigned_to uuid,p_note text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.operational_tasks%rowtype;v_reference text;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_assigned_to is not null and not exists(select 1 from public.staff_profiles where shop_id=v_shop and user_id=p_assigned_to and active) then raise exception 'Assigned staff member is not active in this shop'; end if;
  if length(trim(coalesce(p_note,'')))<3 then raise exception 'Assignment note must contain at least 3 characters'; end if;
  select * into v_row from public.operational_tasks where id=p_task_id and shop_id=v_shop for update;
  if v_row.id is null or v_row.status not in('open','accepted') then raise exception 'Only open or accepted tasks can be reassigned'; end if;
  update public.operational_tasks set assigned_to=p_assigned_to,status='open',accepted_by=null,accepted_at=null,updated_at=now() where id=v_row.id;
  insert into public.operational_task_events(shop_id,task_id,action,from_status,to_status,note,details,performed_by)
  values(v_shop,v_row.id,'assigned',v_row.status,'open',trim(p_note),jsonb_build_object('from_assigned_to',v_row.assigned_to,'assigned_to',p_assigned_to),auth.uid());
  v_reference:='TASK-'||to_char(v_row.business_date,'YYYYMMDD')||'-'||lpad(v_row.task_number::text,6,'0');
  return jsonb_build_object('id',v_row.id,'reference',v_reference,'status','open','assigned_to',p_assigned_to);
end $$;

create or replace function public.accept_operational_task(p_task_id uuid,p_note text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.operational_tasks%rowtype;v_reference text;
begin
  if auth.uid() is null or v_shop is null then raise exception 'Active staff access required'; end if;
  if length(trim(coalesce(p_note,'')))<3 then raise exception 'Acceptance note must contain at least 3 characters'; end if;
  select * into v_row from public.operational_tasks where id=p_task_id and shop_id=v_shop for update;
  if v_row.id is null or v_row.status<>'open' then raise exception 'Open operational task not found'; end if;
  if v_row.assigned_to is not null and v_row.assigned_to<>auth.uid() then raise exception 'This task is assigned to another staff member'; end if;
  update public.operational_tasks set assigned_to=coalesce(v_row.assigned_to,auth.uid()),accepted_by=auth.uid(),accepted_at=now(),status='accepted',updated_at=now() where id=v_row.id;
  insert into public.operational_task_events(shop_id,task_id,action,from_status,to_status,note,details,performed_by)
  values(v_shop,v_row.id,'accepted','open','accepted',trim(p_note),jsonb_build_object('assigned_to',coalesce(v_row.assigned_to,auth.uid())),auth.uid());
  v_reference:='TASK-'||to_char(v_row.business_date,'YYYYMMDD')||'-'||lpad(v_row.task_number::text,6,'0');
  return jsonb_build_object('id',v_row.id,'reference',v_reference,'status','accepted');
end $$;

create or replace function public.complete_operational_task(p_task_id uuid,p_note text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.operational_tasks%rowtype;v_reference text;
begin
  if auth.uid() is null or v_shop is null then raise exception 'Active staff access required'; end if;
  if length(trim(coalesce(p_note,'')))<5 then raise exception 'Completion note must contain at least 5 characters'; end if;
  select * into v_row from public.operational_tasks where id=p_task_id and shop_id=v_shop for update;
  if v_row.id is null or v_row.status<>'accepted' then raise exception 'Accepted operational task not found'; end if;
  if v_row.assigned_to<>auth.uid() and not public.is_admin() then raise exception 'Only the assigned staff member or an administrator can complete this task'; end if;
  update public.operational_tasks set status='completed',completed_by=auth.uid(),completed_at=now(),completion_note=trim(p_note),updated_at=now() where id=v_row.id;
  insert into public.operational_task_events(shop_id,task_id,action,from_status,to_status,note,performed_by)
  values(v_shop,v_row.id,'completed','accepted','completed',trim(p_note),auth.uid());
  v_reference:='TASK-'||to_char(v_row.business_date,'YYYYMMDD')||'-'||lpad(v_row.task_number::text,6,'0');
  return jsonb_build_object('id',v_row.id,'reference',v_reference,'status','completed');
end $$;

create or replace function public.review_operational_task(p_task_id uuid,p_action text,p_note text) returns jsonb
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.operational_tasks%rowtype;v_to text;v_reference text;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_action not in('verify','reopen','cancel') then raise exception 'Invalid review action'; end if;
  if length(trim(coalesce(p_note,'')))<5 then raise exception 'Review note must contain at least 5 characters'; end if;
  select * into v_row from public.operational_tasks where id=p_task_id and shop_id=v_shop for update;
  if v_row.id is null then raise exception 'Operational task not found'; end if;
  if p_action='verify' then
    if v_row.status<>'completed' then raise exception 'Only completed tasks can be verified'; end if;
    v_to:='verified';
    update public.operational_tasks set status=v_to,verified_by=auth.uid(),verified_at=now(),verification_note=trim(p_note),updated_at=now() where id=v_row.id;
  elsif p_action='reopen' then
    if v_row.status not in('completed','verified') then raise exception 'Only completed or verified tasks can be reopened'; end if;
    v_to:='accepted';
    update public.operational_tasks set status=v_to,completed_by=null,completed_at=null,completion_note=null,verified_by=null,verified_at=null,verification_note=null,updated_at=now() where id=v_row.id;
  else
    if v_row.status in('verified','cancelled') then raise exception 'Verified or cancelled tasks cannot be cancelled'; end if;
    v_to:='cancelled';
    update public.operational_tasks set status=v_to,verification_note=trim(p_note),verified_by=auth.uid(),verified_at=now(),updated_at=now() where id=v_row.id;
  end if;
  insert into public.operational_task_events(shop_id,task_id,action,from_status,to_status,note,performed_by)
  values(v_shop,v_row.id,case p_action when 'verify' then 'verified' when 'reopen' then 'reopened' else 'cancelled' end,v_row.status,v_to,trim(p_note),auth.uid());
  v_reference:='TASK-'||to_char(v_row.business_date,'YYYYMMDD')||'-'||lpad(v_row.task_number::text,6,'0');
  return jsonb_build_object('id',v_row.id,'reference',v_reference,'status',v_to);
end $$;

create or replace function public.get_operational_task_board(p_limit integer default 100) returns jsonb
language plpgsql security definer stable set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_limit integer:=greatest(1,least(coalesce(p_limit,100),200));
begin
  if auth.uid() is null or v_shop is null then raise exception 'Active staff access required'; end if;
  return jsonb_build_object(
    'metrics',jsonb_build_object(
      'open',(select count(*) from public.operational_tasks where shop_id=v_shop and status in('open','accepted')),
      'overdue',(select count(*) from public.operational_tasks where shop_id=v_shop and status in('open','accepted') and due_at is not null and due_at<now()),
      'awaiting_review',(select count(*) from public.operational_tasks where shop_id=v_shop and status='completed'),
      'verified',(select count(*) from public.operational_tasks where shop_id=v_shop and status='verified')
    ),
    'staff',(select coalesce(jsonb_agg(jsonb_build_object('user_id',sp.user_id,'display_name',sp.display_name,'role',sp.role) order by sp.display_name),'[]'::jsonb) from public.staff_profiles sp where sp.shop_id=v_shop and sp.active),
    'tasks',(select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) from(
      select t.id,'TASK-'||to_char(t.business_date,'YYYYMMDD')||'-'||lpad(t.task_number::text,6,'0') reference,t.business_date,t.title,t.description,t.priority,t.status,t.source_type,t.source_reference,t.assigned_to,t.due_at,t.created_at,t.accepted_at,t.completed_at,t.completion_note,t.verified_at,t.verification_note,t.updated_at,
        coalesce(creator.display_name,'Former staff') created_by_name,coalesce(assignee.display_name,'Unassigned') assigned_to_name,coalesce(completer.display_name,'—') completed_by_name,coalesce(verifier.display_name,'—') verified_by_name,
        t.assigned_to=auth.uid() assigned_to_me,t.created_by=auth.uid() created_by_me,
        (select count(*) from public.operational_task_events e where e.task_id=t.id) event_count
      from public.operational_tasks t
      left join public.staff_profiles creator on creator.shop_id=t.shop_id and creator.user_id=t.created_by
      left join public.staff_profiles assignee on assignee.shop_id=t.shop_id and assignee.user_id=t.assigned_to
      left join public.staff_profiles completer on completer.shop_id=t.shop_id and completer.user_id=t.completed_by
      left join public.staff_profiles verifier on verifier.shop_id=t.shop_id and verifier.user_id=t.verified_by
      where t.shop_id=v_shop order by t.created_at desc limit v_limit
    )x)
  );
end $$;

