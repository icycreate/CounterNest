language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_base jsonb;v_export uuid;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  v_base:=public.export_business_backup_phase332_base();v_export:=(v_base->>'export_id')::uuid;
  update public.backup_exports set schema_version='1.16.0' where id=v_export and shop_id=v_shop;
  return (v_base-'schema_version')||jsonb_build_object(
    'schema_version','1.16.0',
    'operational_tasks',(select coalesce(jsonb_agg(to_jsonb(t)),'[]'::jsonb) from public.operational_tasks t where shop_id=v_shop),
    'operational_task_events',(select coalesce(jsonb_agg(to_jsonb(t)),'[]'::jsonb) from public.operational_task_events t where shop_id=v_shop)
  );
end $$;

