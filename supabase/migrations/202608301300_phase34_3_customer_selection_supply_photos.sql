-- CounterNest POS v1.26.0 / Phase 34.3
-- Customer product-selection display -> targeted POS queue, plus supply-receipt photo attachments.

-- ---------------------------------------------------------------------------
-- Customer display configuration and selection queue
-- ---------------------------------------------------------------------------
create table if not exists public.customer_display_configs (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null unique references public.shops(id) on delete cascade,
  access_token text not null unique default (replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-','')),
  enabled boolean not null default true,
  target_labels text[] not null default array['Main POS']::text[],
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint customer_display_targets_nonempty check (cardinality(target_labels) between 1 and 12)
);

create table if not exists public.customer_selection_requests (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  display_config_id uuid not null references public.customer_display_configs(id) on delete restrict,
  target_station_label text not null,
  customer_note text,
  status text not null default 'pending' check(status in('pending','loaded','dismissed')),
  total_snapshot numeric(12,2) not null default 0 check(total_snapshot>=0),
  created_at timestamptz not null default now(),
  loaded_at timestamptz,
  loaded_by uuid references auth.users(id) on delete set null,
  dismissed_at timestamptz,
  dismissed_by uuid references auth.users(id) on delete set null,
  dismiss_reason text
);

create table if not exists public.customer_selection_items (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.customer_selection_requests(id) on delete cascade,
  shop_id uuid not null references public.shops(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete restrict,
  product_name_snapshot text not null,
  unit_price_snapshot numeric(12,2) not null check(unit_price_snapshot>=0),
  quantity integer not null check(quantity between 1 and 20),
  line_total numeric(12,2) generated always as(round(unit_price_snapshot*quantity,2)) stored
);

create index if not exists customer_selection_queue_idx on public.customer_selection_requests(shop_id,target_station_label,status,created_at);
create index if not exists customer_selection_items_request_idx on public.customer_selection_items(request_id);

alter table public.customer_display_configs enable row level security;
alter table public.customer_selection_requests enable row level security;
alter table public.customer_selection_items enable row level security;

