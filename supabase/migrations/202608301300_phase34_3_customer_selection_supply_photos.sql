-- Extend the older finished-product stock receiving report with photo count.
create or replace function public.get_stock_receiving() returns jsonb language plpgsql security definer stable set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  return jsonb_build_object(
    'suppliers',(select coalesce(jsonb_agg(to_jsonb(x) order by x.name),'[]'::jsonb) from(select id,name,contact_name,phone,email,active from public.suppliers where shop_id=v_shop)x),
    'receipts',(select coalesce(jsonb_agg(to_jsonb(x) order by x.received_at desc),'[]'::jsonb) from(
      select r.id,r.received_at,s.name supplier_name,p.name product_name,r.quantity,r.unit_cost,r.total_cost,r.invoice_reference,r.note,coalesce(sp.display_name,'Former staff') received_by_name,
        (select count(*) from public.inventory_supply_attachments a where a.shop_id=r.shop_id and a.source_type='stock_receipt' and a.source_id=r.id) attachment_count
      from public.stock_receipts r join public.suppliers s on s.id=r.supplier_id join public.products p on p.id=r.product_id left join public.staff_profiles sp on sp.user_id=r.received_by and sp.shop_id=r.shop_id where r.shop_id=v_shop order by r.received_at desc limit 100
    )x)
  );
end $$;
revoke all on function public.get_stock_receiving() from public;
grant execute on function public.get_stock_receiving() to authenticated;

