create or replace function public.ensure_customer_display_config()
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_row public.customer_display_configs%rowtype;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if v_shop is null then raise exception 'Shop context is required'; end if;
  insert into public.customer_display_configs(shop_id,created_by)
  values(v_shop,auth.uid()) on conflict(shop_id) do nothing;
  select * into v_row from public.customer_display_configs where shop_id=v_shop;
  return jsonb_build_object('id',v_row.id,'access_token',v_row.access_token,'enabled',v_row.enabled,'target_labels',v_row.target_labels,'updated_at',v_row.updated_at);
end $$;

create or replace function public.update_customer_display_config(p_enabled boolean,p_target_labels text[],p_rotate_token boolean default false)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_targets text[];v_row public.customer_display_configs%rowtype;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  select array_agg(x order by ord) into v_targets
  from (
    select distinct on (lower(trim(value))) trim(value) value, ord
    from unnest(coalesce(p_target_labels,array[]::text[])) with ordinality as t(value,ord)
    where nullif(trim(value),'') is not null
    order by lower(trim(value)), ord
  ) x;
  if coalesce(cardinality(v_targets),0)<1 or cardinality(v_targets)>12 then raise exception 'Enter between 1 and 12 POS station labels'; end if;
  insert into public.customer_display_configs(shop_id,created_by,target_labels,enabled)
  values(v_shop,auth.uid(),v_targets,coalesce(p_enabled,true)) on conflict(shop_id) do nothing;
  update public.customer_display_configs
  set enabled=coalesce(p_enabled,true),target_labels=v_targets,
      access_token=case when coalesce(p_rotate_token,false) then replace(gen_random_uuid()::text,'-','')||replace(gen_random_uuid()::text,'-','') else access_token end,
      updated_at=now()
  where shop_id=v_shop returning * into v_row;
  return jsonb_build_object('id',v_row.id,'access_token',v_row.access_token,'enabled',v_row.enabled,'target_labels',v_row.target_labels,'updated_at',v_row.updated_at);
end $$;

-- Public/token-scoped catalog. No authenticated session is required; the long token is the capability.
create or replace function public.get_customer_display_catalog(p_token text)
returns jsonb language plpgsql security definer stable set search_path=public as $$
declare v_cfg public.customer_display_configs%rowtype;v_shop public.shops%rowtype;
begin
  select * into v_cfg from public.customer_display_configs where access_token=p_token and enabled;
  if v_cfg.id is null then raise exception 'Customer display is unavailable or the access link is invalid'; end if;
  select * into v_shop from public.shops where id=v_cfg.shop_id;
  return jsonb_build_object(
    'shop_name',v_shop.name,'logo_url',v_shop.logo_url,'currency',coalesce(v_shop.currency,'USD'),
    'targets',to_jsonb(v_cfg.target_labels),
    'products',(select coalesce(jsonb_agg(to_jsonb(x) order by x.category_name,x.name),'[]'::jsonb) from(
      select p.id,p.name,p.price,p.image_url,p.icon_emoji,coalesce(c.name,'Other') category_name,(p.stock>0) available
      from public.products p left join public.categories c on c.id=p.category_id
      where p.shop_id=v_cfg.shop_id and p.active
    )x)
  );
end $$;

create or replace function public.submit_customer_selection(p_token text,p_target_station_label text,p_items jsonb,p_customer_note text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_cfg public.customer_display_configs%rowtype;v_request uuid;v_number bigint;v_line record;v_product public.products%rowtype;v_count integer:=0;v_total numeric:=0;
begin
  select * into v_cfg from public.customer_display_configs where access_token=p_token and enabled;
  if v_cfg.id is null then raise exception 'Customer display is unavailable or the access link is invalid'; end if;
  if nullif(trim(p_target_station_label),'') is null or not (trim(p_target_station_label)=any(v_cfg.target_labels)) then raise exception 'Select a valid POS station'; end if;
  if jsonb_typeof(coalesce(p_items,'[]'::jsonb))<>'array' or jsonb_array_length(coalesce(p_items,'[]'::jsonb))=0 then raise exception 'Select at least one product'; end if;
  if jsonb_array_length(p_items)>30 then raise exception 'A customer request can contain at most 30 product lines'; end if;
  if exists(select 1 from jsonb_to_recordset(p_items) as x(product_id uuid,quantity integer) where x.product_id is null or x.quantity is null or x.quantity<1 or x.quantity>20) then
    raise exception 'Each product quantity must be between 1 and 20';
  end if;
  if (select count(*) from public.customer_selection_requests where display_config_id=v_cfg.id and status='pending')>=50 then
    raise exception 'The customer selection queue is full. Please ask staff for assistance.';
  end if;
  insert into public.customer_selection_requests(shop_id,display_config_id,target_station_label,customer_note)
  values(v_cfg.shop_id,v_cfg.id,trim(p_target_station_label),nullif(left(trim(coalesce(p_customer_note,'')),180),'')) returning id,request_number into v_request,v_number;
  for v_line in
    select product_id,sum(quantity)::integer quantity
    from jsonb_to_recordset(p_items) as x(product_id uuid,quantity integer)
    group by product_id
  loop
    if v_line.product_id is null or v_line.quantity is null or v_line.quantity<1 or v_line.quantity>20 then raise exception 'Each product quantity must be between 1 and 20'; end if;
    select * into v_product from public.products where id=v_line.product_id and shop_id=v_cfg.shop_id and active for share;
    if v_product.id is null then raise exception 'A selected product is no longer available'; end if;
    if v_product.stock<v_line.quantity then raise exception '% does not have enough stock for the requested quantity',v_product.name; end if;
    insert into public.customer_selection_items(request_id,shop_id,product_id,product_name_snapshot,unit_price_snapshot,quantity)
    values(v_request,v_cfg.shop_id,v_product.id,v_product.name,v_product.price,v_line.quantity);
    v_count:=v_count+1;v_total:=v_total+round(v_product.price*v_line.quantity,2);
  end loop;
  if v_count=0 then raise exception 'Select at least one product'; end if;
  update public.customer_selection_requests set total_snapshot=round(v_total,2) where id=v_request;
  return jsonb_build_object('request_id',v_request,'request_number',v_number,'total',round(v_total,2),'target_station_label',trim(p_target_station_label));
end $$;

create or replace function public.get_customer_selection_queue(p_station_label text)
returns jsonb language plpgsql security definer stable set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();
begin
  if auth.uid() is null or v_shop is null then raise exception 'Staff sign-in is required'; end if;
  if nullif(trim(p_station_label),'') is null then return '[]'::jsonb; end if;
  return (select coalesce(jsonb_agg(to_jsonb(q) order by q.created_at),'[]'::jsonb) from(
    select r.id,r.request_number,r.target_station_label,r.customer_note,r.total_snapshot,r.created_at,
      (select coalesce(jsonb_agg(jsonb_build_object('product_id',i.product_id,'product_name',i.product_name_snapshot,'unit_price',i.unit_price_snapshot,'quantity',i.quantity) order by i.product_name_snapshot),'[]'::jsonb) from public.customer_selection_items i where i.request_id=r.id) items
    from public.customer_selection_requests r
    where r.shop_id=v_shop and r.status='pending' and lower(r.target_station_label)=lower(trim(p_station_label))
    order by r.created_at
  )q);
end $$;

create or replace function public.claim_customer_selection(p_request_id uuid,p_station_label text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_request public.customer_selection_requests%rowtype;
begin
  if auth.uid() is null or v_shop is null then raise exception 'Staff sign-in is required'; end if;
  select * into v_request from public.customer_selection_requests where id=p_request_id and shop_id=v_shop for update;
  if v_request.id is null then raise exception 'Customer request not found'; end if;
  if v_request.status<>'pending' then raise exception 'Customer request has already been handled'; end if;
  if lower(v_request.target_station_label)<>lower(trim(coalesce(p_station_label,''))) then raise exception 'This request belongs to a different POS station'; end if;
  update public.customer_selection_requests set status='loaded',loaded_at=now(),loaded_by=auth.uid() where id=v_request.id;
  return jsonb_build_object('request_id',v_request.id,'request_number',v_request.request_number,'customer_note',v_request.customer_note,'items',
    (select coalesce(jsonb_agg(jsonb_build_object('product_id',i.product_id,'product_name',i.product_name_snapshot,'unit_price',i.unit_price_snapshot,'quantity',i.quantity)),'[]'::jsonb) from public.customer_selection_items i where i.request_id=v_request.id));
end $$;

create or replace function public.dismiss_customer_selection(p_request_id uuid,p_station_label text,p_reason text default null)
returns void language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_request public.customer_selection_requests%rowtype;
begin
  if auth.uid() is null or v_shop is null then raise exception 'Staff sign-in is required'; end if;
  select * into v_request from public.customer_selection_requests where id=p_request_id and shop_id=v_shop for update;
  if v_request.id is null or v_request.status<>'pending' then raise exception 'Pending customer request not found'; end if;
  if lower(v_request.target_station_label)<>lower(trim(coalesce(p_station_label,''))) then raise exception 'This request belongs to a different POS station'; end if;
  update public.customer_selection_requests set status='dismissed',dismissed_at=now(),dismissed_by=auth.uid(),dismiss_reason=nullif(left(trim(coalesce(p_reason,'')),180),'') where id=v_request.id;
end $$;

