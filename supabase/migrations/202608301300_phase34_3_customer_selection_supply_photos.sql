create or replace function public.add_inventory_supply_attachment(p_source_type text,p_source_id uuid,p_storage_path text,p_original_name text,p_mime_type text,p_size_bytes bigint)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_id uuid;v_valid boolean:=false;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_source_type='stock_receipt' then select exists(select 1 from public.stock_receipts where id=p_source_id and shop_id=v_shop) into v_valid;
  elsif p_source_type='ingredient_purchase_receipt' then select exists(select 1 from public.ingredient_purchase_receipts where id=p_source_id and shop_id=v_shop) into v_valid;
  else raise exception 'Unsupported supply attachment source'; end if;
  if not v_valid then raise exception 'Inventory receipt not found'; end if;
  if split_part(p_storage_path,'/',1)<>v_shop::text then raise exception 'Storage path must belong to the current shop'; end if;
  if lower(p_mime_type) not in('image/jpeg','image/png','image/webp') or p_size_bytes<1 or p_size_bytes>8388608 then raise exception 'Supply photo must be JPG, PNG, or WebP and 8 MB or smaller'; end if;
  insert into public.inventory_supply_attachments(shop_id,source_type,source_id,storage_path,original_name,mime_type,size_bytes,uploaded_by)
  values(v_shop,p_source_type,p_source_id,p_storage_path,left(coalesce(p_original_name,'supply-photo'),180),lower(p_mime_type),p_size_bytes,auth.uid()) returning id into v_id;
  return v_id;
end $$;

create or replace function public.get_inventory_supply_attachments(p_source_type text,p_source_id uuid)
returns jsonb language plpgsql security definer stable set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  return (select coalesce(jsonb_agg(jsonb_build_object('id',id,'storage_path',storage_path,'original_name',original_name,'mime_type',mime_type,'size_bytes',size_bytes,'uploaded_at',uploaded_at) order by uploaded_at desc),'[]'::jsonb) from public.inventory_supply_attachments where shop_id=v_shop and source_type=p_source_type and source_id=p_source_id);
end $$;

revoke all on function public.add_inventory_supply_attachment(text,uuid,text,text,text,bigint) from public;
