create or replace function public.maintain_ingredient_lots_from_movement() returns trigger
language plpgsql security definer set search_path=public as $$
declare
  v_needed numeric;v_take numeric;v_lot public.ingredient_lots%rowtype;v_production uuid;v_output_lot uuid;
  v_source_total numeric;v_alloc record;
begin
  -- Ordinary positive corrections remain untracked. Conversion outputs are explicitly traceable.
  if new.quantity_delta>0 and new.movement_type='conversion_output' then
    insert into public.ingredient_lots(shop_id,ingredient_id,lot_code,received_quantity,remaining_quantity,unit_cost_snapshot,status,received_at,created_by)
    values(new.shop_id,new.ingredient_id,'CONV-'||upper(left(coalesce(new.reference_id,new.id)::text,8))||'-'||upper(left(new.id::text,6)),new.quantity_delta,new.quantity_delta,coalesce(new.unit_cost,0),'active',new.created_at,new.created_by)
    returning id into v_output_lot;
    insert into public.ingredient_lot_events(shop_id,lot_id,action,quantity,details,performed_by)
    values(new.shop_id,v_output_lot,'created',new.quantity_delta,jsonb_build_object('source','ingredient conversion','conversion_run_id',new.reference_id,'movement_id',new.id,'traceability','derived'),new.created_by);

    select coalesce(sum(a.quantity_allocated),0) into v_source_total
    from public.ingredient_lot_allocations a
    join public.ingredient_inventory_movements m on m.id=a.inventory_movement_id
    where m.shop_id=new.shop_id and m.reference_type='ingredient_conversion_run' and m.reference_id=new.reference_id and m.movement_type='conversion_input';

    if v_source_total>0 then
      for v_alloc in
        select a.lot_id,sum(a.quantity_allocated) quantity_allocated
        from public.ingredient_lot_allocations a
        join public.ingredient_inventory_movements m on m.id=a.inventory_movement_id
        where m.shop_id=new.shop_id and m.reference_type='ingredient_conversion_run' and m.reference_id=new.reference_id and m.movement_type='conversion_input'
        group by a.lot_id
      loop
        insert into public.ingredient_conversion_lot_links(shop_id,run_id,source_lot_id,output_lot_id,source_quantity,output_quantity_attributed)
        values(new.shop_id,new.reference_id,v_alloc.lot_id,v_output_lot,v_alloc.quantity_allocated,round(new.quantity_delta*(v_alloc.quantity_allocated/v_source_total),3))
        on conflict(run_id,source_lot_id,output_lot_id) do nothing;
      end loop;
    end if;
    return new;
  end if;

  if new.quantity_delta>0 and(new.movement_type in('opening','adjustment','correction','variance','substitution') or(new.movement_type='receipt' and new.reference_type='ingredient_receipt')) then
    insert into public.ingredient_lots(shop_id,ingredient_id,lot_code,received_quantity,remaining_quantity,unit_cost_snapshot,status,received_at,created_by)
    values(new.shop_id,new.ingredient_id,'AUTO-'||upper(left(new.id::text,12)),new.quantity_delta,new.quantity_delta,coalesce(new.unit_cost,0),'active',new.created_at,new.created_by) returning * into v_lot;
    insert into public.ingredient_lot_events(shop_id,lot_id,action,quantity,details,performed_by)
    values(new.shop_id,v_lot.id,'created',new.quantity_delta,jsonb_build_object('source','inventory movement','movement_type',new.movement_type,'traceability','untracked'),new.created_by);
    return new;
  end if;

  if new.quantity_delta>=0 or new.movement_type not in('production','waste','adjustment','correction','conversion_input','variance','substitution') or new.reference_type='ingredient_lot_disposal' then return new; end if;
  v_needed:=-new.quantity_delta;
  if new.reference_type='production_batch' then v_production:=new.reference_id; end if;
  for v_lot in
    select * from public.ingredient_lots l where l.shop_id=new.shop_id and l.ingredient_id=new.ingredient_id and l.remaining_quantity>0
      and(case when new.movement_type in('production','conversion_input','substitution') then l.status='active' and(l.expires_on is null or l.expires_on>=current_date) else l.status in('active','recalled') end)
    order by(l.expires_on is null),l.expires_on,l.received_at,l.id for update
  loop
    exit when v_needed<=0;
    v_take:=least(v_needed,v_lot.remaining_quantity);
    update public.ingredient_lots set remaining_quantity=remaining_quantity-v_take,status=case when remaining_quantity-v_take<=0 then 'depleted' else status end,updated_at=now() where id=v_lot.id;
    insert into public.ingredient_lot_allocations(shop_id,lot_id,inventory_movement_id,production_batch_id,quantity_allocated)
    values(new.shop_id,v_lot.id,new.id,v_production,v_take);
    insert into public.ingredient_lot_events(shop_id,lot_id,action,quantity,details,performed_by)
    values(new.shop_id,v_lot.id,'allocated',v_take,jsonb_build_object('movement_type',new.movement_type,'reference_type',new.reference_type,'reference_id',new.reference_id),new.created_by);
    v_needed:=v_needed-v_take;
  end loop;
  if v_needed>0 then
    if new.movement_type in('production','conversion_input','substitution') then raise exception 'Insufficient usable non-expired, non-recalled ingredient lots';
    else raise exception 'Ingredient lot balances do not cover this stock reduction'; end if;
  end if;
  return new;
end $$;

drop trigger if exists maintain_ingredient_lots_trigger on public.ingredient_inventory_movements;
create trigger maintain_ingredient_lots_trigger after insert on public.ingredient_inventory_movements for each row execute function public.maintain_ingredient_lots_from_movement();

create or replace function public.upsert_ingredient_conversion_rule(
  p_rule_id uuid,p_name text,p_source_ingredient_id uuid,p_source_quantity numeric,p_note text,p_active boolean,p_outputs jsonb
) returns uuid
language plpgsql security definer set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();v_id uuid;v_source public.ingredients%rowtype;v_output record;v_cost_share numeric:=0;v_count integer:=0;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if nullif(trim(p_name),'') is null or p_source_quantity is null or p_source_quantity<=0 then raise exception 'Rule name and positive source quantity are required'; end if;
  select * into v_source from public.ingredients where id=p_source_ingredient_id and shop_id=v_shop and active;
  if v_source.id is null then raise exception 'Active source ingredient not found'; end if;
  if v_source.base_unit='each' and p_source_quantity<>trunc(p_source_quantity) then raise exception 'Countable source ingredients must use whole units'; end if;
  for v_output in select * from jsonb_to_recordset(coalesce(p_outputs,'[]'::jsonb)) as x(ingredient_id uuid,output_label text,output_quantity numeric,track_inventory boolean,cost_share_percent numeric,sort_order integer) loop
    v_count:=v_count+1;
    if nullif(trim(v_output.output_label),'') is null or coalesce(v_output.output_quantity,0)<=0 then raise exception 'Every conversion output requires a label and positive quantity'; end if;
    if coalesce(v_output.track_inventory,true) then
      if v_output.ingredient_id is null or not exists(select 1 from public.ingredients where id=v_output.ingredient_id and shop_id=v_shop and active) then raise exception 'Tracked outputs require an active ingredient'; end if;
      if v_output.ingredient_id=p_source_ingredient_id then raise exception 'Source ingredient cannot also be a tracked output'; end if;
      v_cost_share:=v_cost_share+coalesce(v_output.cost_share_percent,0);
    end if;
  end loop;
  if v_count=0 then raise exception 'At least one output is required'; end if;
  if abs(v_cost_share-100)>0.01 then raise exception 'Cost shares for tracked outputs must total 100 percent'; end if;

  if p_rule_id is null then
    insert into public.ingredient_conversion_rules(shop_id,name,source_ingredient_id,source_quantity,note,active,created_by,updated_by)
    values(v_shop,trim(p_name),p_source_ingredient_id,p_source_quantity,nullif(trim(p_note),''),coalesce(p_active,true),auth.uid(),auth.uid()) returning id into v_id;
  else
    if not exists(select 1 from public.ingredient_conversion_rules where id=p_rule_id and shop_id=v_shop) then raise exception 'Conversion rule not found'; end if;
    update public.ingredient_conversion_rules set name=trim(p_name),source_ingredient_id=p_source_ingredient_id,source_quantity=p_source_quantity,note=nullif(trim(p_note),''),active=coalesce(p_active,true),updated_by=auth.uid(),updated_at=now() where id=p_rule_id;
    v_id:=p_rule_id;delete from public.ingredient_conversion_outputs where rule_id=v_id;
  end if;
  insert into public.ingredient_conversion_outputs(shop_id,rule_id,ingredient_id,output_label,output_quantity,track_inventory,cost_share_percent,sort_order)
  select v_shop,v_id,x.ingredient_id,trim(x.output_label),x.output_quantity,coalesce(x.track_inventory,true),coalesce(x.cost_share_percent,0),coalesce(x.sort_order,0)
  from jsonb_to_recordset(p_outputs) as x(ingredient_id uuid,output_label text,output_quantity numeric,track_inventory boolean,cost_share_percent numeric,sort_order integer);
  return v_id;
end $$;

create or replace function public.run_ingredient_conversion(p_rule_id uuid,p_source_quantity numeric,p_note text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_shop uuid:=public.current_shop_id();v_rule public.ingredient_conversion_rules%rowtype;v_source public.ingredients%rowtype;v_target public.ingredients%rowtype;v_run uuid;v_balance numeric;v_scale numeric;v_source_cost numeric;v_out record;v_qty numeric;v_unit_cost numeric;v_old_value numeric;v_new_balance numeric;v_new_average numeric;v_outputs jsonb:='[]'::jsonb;
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_source_quantity is null or p_source_quantity<=0 then raise exception 'Source quantity must be greater than zero'; end if;
  select * into v_rule from public.ingredient_conversion_rules where id=p_rule_id and shop_id=v_shop and active for update;
  if v_rule.id is null then raise exception 'Active conversion rule not found'; end if;
  select * into v_source from public.ingredients where id=v_rule.source_ingredient_id and shop_id=v_shop and active for update;
  if v_source.id is null then raise exception 'Source ingredient not found'; end if;
  if v_source.base_unit='each' and p_source_quantity<>trunc(p_source_quantity) then raise exception 'Countable source ingredients must be converted in whole units'; end if;
  if v_source.current_quantity<p_source_quantity then raise exception 'Insufficient source stock'; end if;
  v_scale:=p_source_quantity/v_rule.source_quantity;v_source_cost:=v_source.average_unit_cost;
  insert into public.ingredient_conversion_runs(shop_id,rule_id,source_ingredient_id,source_quantity,source_unit_cost_snapshot,note,performed_by)
  values(v_shop,v_rule.id,v_source.id,p_source_quantity,v_source_cost,nullif(trim(p_note),''),auth.uid()) returning id into v_run;
  v_balance:=v_source.current_quantity-p_source_quantity;
  update public.ingredients set current_quantity=v_balance,updated_at=now() where id=v_source.id;
  insert into public.ingredient_inventory_movements(shop_id,ingredient_id,movement_type,quantity_delta,unit_cost,balance_after,reason,reference_type,reference_id,created_by)
  values(v_shop,v_source.id,'conversion_input',-p_source_quantity,v_source_cost,v_balance,'Ingredient conversion: '||v_rule.name,'ingredient_conversion_run',v_run,auth.uid());

  for v_out in select o.* from public.ingredient_conversion_outputs o where o.rule_id=v_rule.id order by o.sort_order,o.created_at
  loop
    v_qty:=round(v_out.output_quantity*v_scale,3);
    if v_out.track_inventory then
      select * into v_target from public.ingredients where id=v_out.ingredient_id and shop_id=v_shop and active for update;
      if v_target.id is null then raise exception 'Tracked conversion output ingredient is unavailable'; end if;
      if v_target.base_unit='each' and v_qty<>trunc(v_qty) then raise exception 'Conversion produces a fractional count for %',v_out.output_label; end if;
      v_unit_cost:=case when v_qty>0 then round((p_source_quantity*v_source_cost*(v_out.cost_share_percent/100))/v_qty,6) else 0 end;
      v_old_value:=v_target.current_quantity*v_target.average_unit_cost;v_new_balance:=v_target.current_quantity+v_qty;
      v_new_average:=case when v_new_balance>0 then round((v_old_value+v_qty*v_unit_cost)/v_new_balance,6) else v_target.average_unit_cost end;
      update public.ingredients set current_quantity=v_new_balance,average_unit_cost=v_new_average,updated_at=now() where id=v_target.id;
      insert into public.ingredient_inventory_movements(shop_id,ingredient_id,movement_type,quantity_delta,unit_cost,balance_after,reason,reference_type,reference_id,created_by)
      values(v_shop,v_out.ingredient_id,'conversion_output',v_qty,v_unit_cost,v_new_balance,'Derived from '||v_source.name||' via '||v_rule.name,'ingredient_conversion_run',v_run,auth.uid());
    else v_unit_cost:=0;v_new_balance:=null; end if;
    insert into public.ingredient_conversion_run_outputs(shop_id,run_id,output_definition_id,ingredient_id,output_label,quantity_produced,unit_cost_snapshot,track_inventory)
    values(v_shop,v_run,v_out.id,v_out.ingredient_id,v_out.output_label,v_qty,v_unit_cost,v_out.track_inventory);
    v_outputs:=v_outputs||jsonb_build_array(jsonb_build_object('label',v_out.output_label,'ingredient_id',v_out.ingredient_id,'quantity',v_qty,'unit',case when v_out.track_inventory then v_target.base_unit else null end,'tracked',v_out.track_inventory,'balance_after',v_new_balance,'unit_cost',v_unit_cost));
  end loop;
  return jsonb_build_object('run_id',v_run,'rule_name',v_rule.name,'source_ingredient_id',v_source.id,'source_quantity',p_source_quantity,'source_balance_after',v_balance,'outputs',v_outputs);
end $$;

create or replace function public.get_ingredient_conversion_overview() returns jsonb
language plpgsql security definer stable set search_path=public as $$
declare v_shop uuid:=public.current_shop_id();
begin
  if auth.uid() is null or not public.is_admin() then raise exception 'Administrator access required'; end if;
  return jsonb_build_object(
    'ingredients',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'name',name,'base_unit',base_unit,'current_quantity',current_quantity,'average_unit_cost',average_unit_cost,'active',active) order by name),'[]'::jsonb) from public.ingredients where shop_id=v_shop and active),
    'rules',(select coalesce(jsonb_agg(to_jsonb(x) order by x.name),'[]'::jsonb) from(
      select r.id,r.name,r.source_ingredient_id,i.name source_name,i.base_unit source_unit,r.source_quantity,r.note,r.active,
      (select coalesce(jsonb_agg(jsonb_build_object('id',o.id,'ingredient_id',o.ingredient_id,'output_label',o.output_label,'output_quantity',o.output_quantity,'track_inventory',o.track_inventory,'cost_share_percent',o.cost_share_percent,'sort_order',o.sort_order,'ingredient_name',oi.name,'base_unit',oi.base_unit) order by o.sort_order,o.created_at),'[]'::jsonb) from public.ingredient_conversion_outputs o left join public.ingredients oi on oi.id=o.ingredient_id where o.rule_id=r.id) outputs
      from public.ingredient_conversion_rules r join public.ingredients i on i.id=r.source_ingredient_id where r.shop_id=v_shop
    )x),
    'recent_runs',(select coalesce(jsonb_agg(to_jsonb(x) order by x.performed_at desc),'[]'::jsonb) from(
      select cr.id,cr.run_number,cr.performed_at,cr.source_quantity,i.name source_name,i.base_unit source_unit,r.name rule_name,coalesce(sp.display_name,'Former staff') performed_by_name,
      (select coalesce(jsonb_agg(jsonb_build_object('label',ro.output_label,'quantity',ro.quantity_produced,'unit_cost',ro.unit_cost_snapshot,'tracked',ro.track_inventory,'ingredient_name',oi.name,'base_unit',oi.base_unit)),'[]'::jsonb) from public.ingredient_conversion_run_outputs ro left join public.ingredients oi on oi.id=ro.ingredient_id where ro.run_id=cr.id) outputs
      from public.ingredient_conversion_runs cr join public.ingredient_conversion_rules r on r.id=cr.rule_id join public.ingredients i on i.id=cr.source_ingredient_id left join public.staff_profiles sp on sp.user_id=cr.performed_by and sp.shop_id=cr.shop_id where cr.shop_id=v_shop limit 50
    )x)
  );
end $$;

