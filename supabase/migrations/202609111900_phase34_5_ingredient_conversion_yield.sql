alter table public.ingredient_inventory_movements drop constraint if exists ingredient_inventory_movements_movement_type_check;
alter table public.ingredient_inventory_movements add constraint ingredient_inventory_movements_movement_type_check
check (movement_type in ('opening','receipt','adjustment','production','waste','correction','conversion_input','conversion_output','variance','substitution'));

create table if not exists public.ingredient_conversion_rules (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  name text not null,
  source_ingredient_id uuid not null references public.ingredients(id) on delete restrict,
  source_quantity numeric(14,3) not null check(source_quantity>0),
  active boolean not null default true,
  note text,
  created_by uuid not null references auth.users(id) on delete restrict,
  updated_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(shop_id,name)
);

create table if not exists public.ingredient_conversion_outputs (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  rule_id uuid not null references public.ingredient_conversion_rules(id) on delete cascade,
  ingredient_id uuid references public.ingredients(id) on delete restrict,
  output_label text not null,
  output_quantity numeric(14,3) not null check(output_quantity>0),
  track_inventory boolean not null default true,
  cost_share_percent numeric(7,4) not null default 0 check(cost_share_percent>=0 and cost_share_percent<=100),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint conversion_output_inventory_target check((track_inventory and ingredient_id is not null) or not track_inventory)
);

create table if not exists public.ingredient_conversion_runs (
  id uuid primary key default gen_random_uuid(),
  run_number bigint generated by default as identity,
  shop_id uuid not null references public.shops(id) on delete cascade,
  rule_id uuid not null references public.ingredient_conversion_rules(id) on delete restrict,
  source_ingredient_id uuid not null references public.ingredients(id) on delete restrict,
  source_quantity numeric(14,3) not null check(source_quantity>0),
  source_unit_cost_snapshot numeric(14,6) not null default 0 check(source_unit_cost_snapshot>=0),
  note text,
  performed_by uuid not null references auth.users(id) on delete restrict,
  performed_at timestamptz not null default now()
);

create table if not exists public.ingredient_conversion_run_outputs (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  run_id uuid not null references public.ingredient_conversion_runs(id) on delete cascade,
  output_definition_id uuid not null references public.ingredient_conversion_outputs(id) on delete restrict,
  ingredient_id uuid references public.ingredients(id) on delete restrict,
  output_label text not null,
  quantity_produced numeric(14,3) not null check(quantity_produced>0),
  unit_cost_snapshot numeric(14,6) not null default 0 check(unit_cost_snapshot>=0),
  track_inventory boolean not null,
  created_at timestamptz not null default now()
);

create table if not exists public.ingredient_conversion_lot_links (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  run_id uuid not null references public.ingredient_conversion_runs(id) on delete cascade,
  source_lot_id uuid not null references public.ingredient_lots(id) on delete restrict,
  output_lot_id uuid not null references public.ingredient_lots(id) on delete restrict,
  source_quantity numeric(14,3) not null check(source_quantity>0),
  output_quantity_attributed numeric(14,3) not null check(output_quantity_attributed>0),
  created_at timestamptz not null default now(),
  unique(run_id,source_lot_id,output_lot_id)
);

