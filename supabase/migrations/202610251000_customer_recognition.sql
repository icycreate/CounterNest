create function public.get_customer_recognition(p_request uuid,p_query text default '') returns jsonb language plpgsql stable security definer set search_path=public as $$
declare r catalogue_preorder_requests;l catalogue_customer_links;n text;matches jsonb;review jsonb;linked jsonb;count_matches integer;label text;
begin
 if not can_review_customer_links() then raise exception 'Customer service access required';end if;
 select * into strict r from catalogue_preorder_requests where id=p_request and shop_id=current_shop_id();
 select * into l from catalogue_customer_links where request_id=r.id and shop_id=r.shop_id;
 n:=recognition_phone(coalesce(r.submission_snapshot->>'phone',r.payload->>'phone',case when r.preferred_method in('phone','sms','whatsapp') then r.contact_value end));
 if not recognition_valid_phone(n) then n:=null;end if;
 select count(*) into count_matches from customers where shop_id=r.shop_id and n is not null and recognition_phone(phone)=n;
 select coalesce(jsonb_agg(to_jsonb(x)),'[]') into matches from(select id,name,phone,active from customers where shop_id=r.shop_id and n is not null and recognition_phone(phone)=n order by active desc,name,id limit 100)x;
 if length(trim(coalesce(p_query,'')))>=2 then
 select coalesce(jsonb_agg(to_jsonb(x)),'[]') into review from(select id,name,phone,active from customers where shop_id=r.shop_id and (name ilike '%'||left(trim(p_query),100)||'%' or id::text=trim(p_query) or (recognition_phone(p_query) is not null and recognition_phone(phone)=recognition_phone(p_query))) order by active desc,name,id limit 20)x;
 end if;
 select jsonb_build_object('id',id,'name',name,'phone',phone,'active',active) into linked from customers where id=l.customer_id and shop_id=r.shop_id;
 label:=case when l.state='linked' then 'Linked Customer' when l.state='guest' then 'Guest Customer' when n is null then 'Unmatched' when count_matches>1 then 'Multiple Matching Customers' when count_matches=0 then 'New Customer' when not (matches->0->>'active')::boolean then 'Archived Customer' when lower(trim(matches->0->>'name'))=lower(trim(r.customer_name)) then 'Existing Customer Found' else 'Possible Customer Match' end;
 return jsonb_build_object('request_id',r.id,'status',label,'revision',coalesce(l.revision,0),'linked',linked,'method',l.method,'confirmed_at',l.confirmed_at,'phone',n,'submitted_phone',coalesce(r.submission_snapshot->>'phone',r.payload->>'phone',case when r.preferred_method in('phone','sms','whatsapp') then r.contact_value end),'submitted_name',coalesce(r.submission_snapshot->>'customer_name',r.customer_name),'candidates',matches,'candidate_count',count_matches,'review',coalesce(review,'[]'),'can_create',n is not null and count_matches=0,'closed',exists(select 1 from scheduled_customer_orders where id=r.scheduled_order_id and (sale_id is not null or status in('completed','cancelled'))));
end$$;

create function public.get_order_customer_recognition(p_order uuid) returns jsonb language plpgsql stable security definer set search_path=public as $$
declare request uuid;
begin
 if not can_review_customer_links() then raise exception 'Customer service access required';end if;
 select id into request from catalogue_preorder_requests where shop_id=current_shop_id() and scheduled_order_id=p_order;
 if request is null then return null;end if;
 return get_customer_recognition(request);
end$$;

create function public.resolve_customer_recognition(p_request uuid,p_revision integer,p_operation uuid,p_action text,p_customer uuid default null,p_reason text default '') returns jsonb language plpgsql security definer set search_path=public as $$
declare r catalogue_preorder_requests;l catalogue_customer_links;o scheduled_customer_orders;c customers;n text;target uuid;args jsonb;prior customer_link_operations;
begin
 if not can_review_customer_links() then raise exception 'Customer service access required';end if;
 if p_operation is null or coalesce(p_action,'') not in('link','guest','create') or length(trim(p_reason))<5 or length(p_reason)>500 then raise exception 'Confirmation reason required';end if;
 select * into strict r from catalogue_preorder_requests where id=p_request and shop_id=current_shop_id() for update;
 args:=jsonb_build_object('action',p_action,'customer',p_customer,'reason',p_reason);
 select * into prior from customer_link_operations where operation_id=p_operation;
 if found then
  if prior.shop_id<>r.shop_id or prior.request_id<>r.id or prior.arguments<>args then raise exception 'Operation key already used';end if;
  return get_customer_recognition(r.id);
 end if;
 select * into l from catalogue_customer_links where request_id=r.id for update;
 if coalesce(l.revision,0) is distinct from p_revision then raise exception 'Customer link changed. Review again.';end if;
 if r.scheduled_order_id is not null then
  select * into strict o from scheduled_customer_orders where id=r.scheduled_order_id and shop_id=r.shop_id for update;
  if o.sale_id is not null or o.status in('completed','cancelled') then raise exception 'Paid or closed orders cannot be relinked';end if;
 end if;
 n:=recognition_phone(coalesce(r.submission_snapshot->>'phone',r.payload->>'phone',case when r.preferred_method in('phone','sms','whatsapp') then r.contact_value end));
 if not recognition_valid_phone(n) then n:=null;end if;
 if p_action='create' then
  if n is null then raise exception 'Valid international phone required';end if;
  -- Serializes the duplicate check with all customer writes, including other customer editors.
  lock table customers in share row exclusive mode;
  if exists(select 1 from customers where shop_id=r.shop_id and (recognition_phone(phone)=n or lower(trim(name))=lower(trim(r.customer_name)))) then raise exception 'Duplicate Customer Warning';end if;
  insert into customers(shop_id,name,phone) values(r.shop_id,r.customer_name,n) returning id into target;
 elsif p_action='link' then
  select * into strict c from customers where id=p_customer and shop_id=r.shop_id for share;
  if not c.active then raise exception 'Restore archived customer before linking';end if;
  target:=c.id;
 end if;
 insert into catalogue_customer_links(request_id,shop_id,customer_id,state,reason,confirmed_by)
 values(r.id,r.shop_id,target,case when target is null then 'guest' else 'linked' end,trim(p_reason),auth.uid())
